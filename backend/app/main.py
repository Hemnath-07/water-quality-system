@app.post("/api/upload-and-train")
async def upload_and_train(
    file: UploadFile = File(...),
    target_column: str = Query("Potability", description="Name of the target classification column")
):
    """
    Accepts a CSV dataset, cleans missing values, handles outliers,
    trains multiple models, and returns comparison metrics and feature importances.
    """
    if not file.filename.endswith(".csv"):
        raise HTTPException(status_code=400, detail="Invalid file type. Please upload a standard CSV file.")

    try:
        contents = await file.read()
        df = pd.read_csv(io.BytesIO(contents))
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Failed to parse CSV file: {str(e)}")

    if target_column not in df.columns:
        raise HTTPException(
            status_code=400,
            detail=f"Target column '{target_column}' not found in dataset. Available columns: {list(df.columns)}"
        )

    # 1. Data Cleaning & Preprocessing
    X_scaled, df_clean = preprocessor.fit_transform(df, target_column=target_column)
    y = df[target_column]

    # 2. Train & Compare ML Models
    evaluations, best_model_name, feature_importance = pipeline.train_and_compare(X_scaled, y)

    # 3. Descriptive Stats for Front-end Charts
    parameter_summary = {}
    for col in df_clean.columns:
        parameter_summary[col] = {
            "mean": round(float(df_clean[col].mean()), 2),
            "std": round(float(df_clean[col].std()), 2),
            "min": round(float(df_clean[col].min()), 2),
            "max": round(float(df_clean[col].max()), 2),
            "median": round(float(df_clean[col].median()), 2)
        }

    return {
        "message": "Dataset successfully processed and models trained.",
        "best_model": best_model_name,
        "model_evaluations": evaluations,
        "feature_importance": feature_importance,
        "parameter_summary": parameter_summary,
        "disclaimer": LEGAL_DISCLAIMER
    }

@app.post("/api/predict")
def predict_sample(sample: SamplePredictionInput):
    """
    Predicts potability for a single set of water parameters.
    """
    if pipeline.best_model is None:
        raise HTTPException(
            status_code=400,
            detail="No trained model found. Please upload a training CSV via /api/upload-and-train first."
        )

    # Convert incoming dict into Pandas DataFrame
    sample_dict = sample.dict()
    input_df = pd.DataFrame([sample_dict])

    # Transform features with preprocessor
    scaled_input, _ = preprocessor.fit_transform(input_df)
    
    # Generate prediction
    predictions, probs = pipeline.predict_sample(scaled_input)
    pred_val = int(predictions[0])
    
    label = "Potable (Safe for Screening Standards)" if pred_val == 1 else "Non-Potable (Unsafe)"
    confidence = float(np.max(probs[0])) if probs else None

    return {
        "prediction_code": pred_val,
        "category": label,
        "confidence": round(confidence, 4) if confidence else "N/A",
        "input_parameters": sample_dict,
        "disclaimer": LEGAL_DISCLAIMER
    }

@app.post("/api/download-report")
def download_pdf_report(sample: SamplePredictionInput):
    """
    Generates and returns a downloadable PDF report summarizing parameter values
    and screening output.
    """
    if pipeline.best_model is None:
        raise HTTPException(
            status_code=400,
            detail="No model trained yet. Please upload a dataset prior to report generation."
        )

    # Process prediction logic
    sample_dict = sample.dict()
    input_df = pd.DataFrame([sample_dict])
    scaled_input, _ = preprocessor.fit_transform(input_df)
    predictions, probs = pipeline.predict_sample(scaled_input)
    
    pred_val = int(predictions[0])
    label = "Potable (Safe)" if pred_val == 1 else "Non-Potable (Unsafe)"
    confidence = float(np.max(probs[0])) if probs else None

    # Generate PDF buffer using utility module
    pdf_bytes = generate_pdf_report(
        sample_data=sample_dict,
        prediction_label=label,
        confidence=confidence,
        model_name=pipeline.best_model_name,
        disclaimer=LEGAL_DISCLAIMER
    )

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": "attachment; filename=Water_Quality_Screening_Report.pdf"}
    )
