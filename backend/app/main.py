# --- Pydantic Data Models ---

class SamplePredictionInput(BaseModel):
    ph: float = Field(..., example=7.2)
    Hardness: float = Field(..., example=190.5)
    Solids: float = Field(..., example=20500.0)
    Chloramines: float = Field(..., example=7.1)
    Sulfate: float = Field(..., example=333.3)
    Conductivity: float = Field(..., example=420.0)
    Organic_carbon: float = Field(..., example=14.2)
