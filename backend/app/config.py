import os
from pathlib import Path
from pydantic_settings import BaseSettings

# Resolve base paths relative to the project root
BASE_DIR = Path(__file__).resolve().parent.parent

class Settings(BaseSettings):
    # Application Setup
    APP_NAME: str = "Smart Water Quality Prediction System"
    APP_VERSION: str = "1.0.0"
    DEBUG: bool = True

    # Server Configuration
    HOST: str = "0.0.0.0"
    PORT: int = 8000

    # Storage Paths
    UPLOAD_DIR: Path = BASE_DIR / "uploads"
    MODEL_DIR: Path = BASE_DIR / "models"

    # ML Pipeline Defaults
    TARGET_COLUMN: str = "Potability"
    RANDOM_STATE: int = 42
    TEST_SIZE: float = 0.2

    # Legal Disclaimer Configuration
    LEGAL_DISCLAIMER: str = (
        "DISCLAIMER: The outputs generated by this system are screening results "
        "derived from computational machine learning models. This report is for "
        "informational purposes only and should NOT be used as a substitute for "
        "certified laboratory water testing."
    )

    class Config:
        env_file = ".env"
        env_file_encoding = "utf-8"

# Instantiate settings
settings = Settings()

# Ensure required directories exist at runtime
settings.UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
settings.MODEL_DIR.mkdir(parents=True, exist_ok=True)
